# Цена у поставщика хранится в минимальных единицах валюты; у иены их нет.
MINOR_UNITS: dict[str, int] = {"JPY": 1}


def to_rub_kop(price_minor: int, currency: str) -> int:
    """Ориентир в копейках по курсу FX_HINT."""
    units = price_minor / MINOR_UNITS.get(currency, 100)
    return round(units * FX_HINT.get(currency, 100.0) * 100)


def region(country: str) -> str:
    return COUNTRY_REGION.get(country, "europe")


