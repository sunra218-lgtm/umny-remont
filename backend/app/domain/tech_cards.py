def step(
    key: str,
    title: str,
    how: str,
    tolerance: str | None = None,
    check: str | None = None,
    mistakes: list[str] | None = None,
    photo: str | None = None,
    *,
    hidden: bool = False,
    inspector: bool = False,
) -> dict[str, Any]:
    return {
        "key": key,
        "title": title,
        "how": how,
        "tolerance": tolerance,
        "check": check,
        "mistakes": mistakes or [],
        "photo": photo,
        "hidden": hidden,
        "inspector": inspector,
    }


def material(
    key: str,
    name: str,
    rate: float,
    per: str,
    unit: str,
    *,
    per_mm: bool = False,
    thickness_mm: float | None = None,
    pack: float | None = None,
    pack_title: str | None = None,
    reserve_pct: int = 10,
    note: str | None = None,
) -> dict[str, Any]:
    return {
        "key": key,
        "name": name,
        "rate": rate,
        "per": per,
        "unit": unit,
        "per_mm": per_mm,
        "thickness_mm": thickness_mm,
        "pack": pack,
        "pack_title": pack_title,
        "reserve_pct": reserve_pct,
        "note": note,
    }


