"""Стартовые технологические карты по типам этапов.

Источник допусков — действующие своды правил и ПУЭ; ссылки указаны в каждой карте и шаге.
Это стартовое наполнение для пилота: до запуска его проверяет инженер технадзора платформы
и отмечает карту проверенной в админке. Пока карта не проверена, бригада и заказчик видят
пометку «ориентир, проверяется инженером».

Шаг карты:
* ``key`` — постоянный код шага (по нему привязаны пункты чек-листа и отметки технадзора);
* ``how`` — как делать; ``tolerance`` — допуск; ``check`` — чем и как проверить;
* ``mistakes`` — частые ошибки; ``photo`` — какой ракурс снять (None — фото не нужно);
* ``hidden`` — скрытые работы (после следующего шага их не будет видно);
* ``inspector`` — пункт проверки инженера на стоп-точке.

Материал: расход ``rate`` на единицу ``per`` (м², м.п., шт); ``per_mm`` — расход на 1 мм
толщины слоя, тогда толщину задаёт ``thickness_mm``; ``pack`` — фасовка; ``reserve_pct`` — запас.
"""

